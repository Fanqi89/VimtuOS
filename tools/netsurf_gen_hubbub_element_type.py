#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""tools/netsurf_gen_hubbub_element_type.py - ★ v0.12.5：手写替身，替掉 libhubbub 的 **gperf** 步骤

libhubbub 的官方 Makefile 里有一条：

    src/treebuilder/autogenerated-element-type.c: src/treebuilder/element-type.gperf
            gperf --output-file=$@.tmp $<
            sed -e 's/^\\(const struct element_type_map\\)/static \\1/' $@.tmp > $@

**本机没有 gperf**（`which gperf` = 无），所以 `element-type.c` 会报
`fatal error: 'treebuilder/autogenerated-element-type.c' file not found`，整个 libhubbub 编不出来。

本脚本不是"假装编过"，而是**按 gperf 的语义手写等价物**：
  * 读 `element-type.gperf` 的关键字段（`%%` 之后），每行 `名字,  枚举`；
  * 生成一个 `wordlist[]` 表（`struct element_type_map { const char *name; element_type type; }`，
    结构体定义在 element-type.h 里，这里**不重复定义**）；
  * 生成 `hubbub_element_type_generated_lookup(const char *s, size_t len)`：
    **大小写不敏感**（.gperf 里的 `%ignore-case`）、**按长度精确匹配**（`%compare-strncmp`），
    返回表项指针；没命中返回 NULL（`element_type.c` 会把它变成 `UNKNOWN`）。

为什么用线性查找而不是完美哈希：表只有 131 个标签名，而且是**只在解析标签名时**调用，
不是热路径；行为一致、可读、可测，比"自己实现一个 perfect hash"风险低一个数量级。
（如实记录：性能低于 gperf 版本，量级是"每次标签名比较 ~131 次 strncmp"，可忽略。）

用法：
  py -3 tools/netsurf_gen_hubbub_element_type.py                 # 写 third_party 里那份（构建脚本调它）
  py -3 tools/netsurf_gen_hubbub_element_type.py --out X.c       # 指定输出
  py -3 tools/netsurf_gen_hubbub_element_type.py --check         # 只校验（不写），打印条目数
退出码：0 = 成功；2 = 输入文件缺失/解析不出条目。
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
HUBBUB = os.path.join(ROOT, "third_party", "netsurf", "libhubbub")


def parse_gperf(path):
    """返回 [(name, ENUM)]。关键字段 = 第一个以 %% 开头的行之后，直到文件结束或下一行 %% 。"""
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        lines = f.read().splitlines()
    try:
        i = next(k for k, ln in enumerate(lines) if ln.strip() == "%%")
    except StopIteration:
        raise SystemExit("gperf 文件里找不到 %%%% 分隔行：%s" % path)
    out = []
    for ln in lines[i + 1:]:
        s = ln.strip()
        if not s or s.startswith("#") or s == "%%":
            continue
        # 形如：  a,                   A
        # 也可能有带引号的名字（本版没有）：  "foo-bar",   FOO
        m = re.match(r'^("?)([^",]+)\1\s*,\s*([A-Z0-9_]+)\s*$', s)
        if not m:
            continue
        out.append((m.group(2), m.group(3)))
    if not out:
        raise SystemExit("gperf 关键字段里一个条目都没解析出来：%s" % path)
    return out


def render(entries):
    L = []
    L.append("/*")
    L.append(" * autogenerated-element-type.c —— **手写替身**（本机没有 gperf）")
    L.append(" *")
    L.append(" * 生成者：tools/netsurf_gen_hubbub_element_type.py（读 src/treebuilder/element-type.gperf）")
    L.append(" * 为什么不用 gperf：msys2 里没有 gperf；这里按 gperf 的语义做**等价的线性查找**")
    L.append(" *   （%ignore-case = 大小写不敏感、%compare-strncmp = 按长度精确匹配）。")
    L.append(" * 语义与官方自动生成物一致；差别只有性能（131 条表项，非热路径）。")
    L.append(" */")
    L.append("")
    L.append("#include <string.h>")
    L.append("")
    L.append("#include \"treebuilder/element-type.h\"")
    L.append("")
    L.append("/* struct element_type_map 已在 element-type.h 里定义，这里只放表本体。 */")
    L.append("static const struct element_type_map wordlist[] = {")
    for name, enum in entries:
        L.append("\t{ \"%s\", %s }," % (name, enum))
    L.append("};")
    L.append("")
    L.append("#define WORDLIST_LEN (sizeof(wordlist) / sizeof(wordlist[0]))")
    L.append("")
    L.append("static int nl_ieq(const char *a, size_t alen, const char *b)")
    L.append("{")
    L.append("\tsize_t i;")
    L.append("\tfor (i = 0; i < alen; i++) {")
    L.append("\t\tunsigned char x = (unsigned char)a[i];")
    L.append("\t\tunsigned char y = (unsigned char)b[i];")
    L.append("\t\tif (y == 0) return 0;\t\t\t/* b 比 a 短 */")
    L.append("\t\tif (x >= 'A' && x <= 'Z') x = (unsigned char)(x - 'A' + 'a');")
    L.append("\t\tif (y >= 'A' && y <= 'Z') y = (unsigned char)(y - 'A' + 'a');")
    L.append("\t\tif (x != y) return 0;")
    L.append("\t}")
    L.append("\treturn b[alen] == 0;\t\t\t\t/* 长度必须相等 */")
    L.append("}")
    L.append("")
    L.append("static const struct element_type_map *hubbub_element_type_generated_lookup(")
    L.append("\t\tconst char *str, size_t len)")
    L.append("{")
    L.append("\tsize_t i;")
    L.append("\tif (str == NULL) return NULL;")
    L.append("\tfor (i = 0; i < WORDLIST_LEN; i++) {")
    L.append("\t\tif (nl_ieq(str, len, wordlist[i].name)) return &wordlist[i];")
    L.append("\t}")
    L.append("\treturn NULL;")
    L.append("}")
    L.append("")
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--gperf", default=os.path.join(HUBBUB, "src", "treebuilder", "element-type.gperf"))
    ap.add_argument("--out", default=os.path.join(HUBBUB, "src", "treebuilder", "autogenerated-element-type.c"))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    if not os.path.exists(args.gperf):
        sys.stderr.write("[HUBBUB-GEN] FAIL 缺 gperf 输入：%s\n" % args.gperf)
        return 2
    entries = parse_gperf(args.gperf)
    text = render(entries)
    if args.check:
        print("[HUBBUB-GEN] check ok=1 entries=%d (gperf=%s)" % (len(entries), args.gperf))
        return 0
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "wb") as f:
        f.write(text.encode("utf-8"))
    print("[HUBBUB-GEN] ok=1 entries=%d bytes=%d -> %s"
          % (len(entries), len(text.encode("utf-8")), args.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
